// Paden gebaseerd op Feather Icons (MIT-licentie, https://feathericons.com).
// Standaard verborgen voor schermlezers: zet de uitleg in de tekst of een aria-label.
function Icon({
  size = '1em',
  className,
  children,
  ...props
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className ? `icon ${className}` : 'icon'}
      {...props}
    >
      {children}
    </svg>
  )
}

